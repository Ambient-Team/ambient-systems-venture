print("--- 1. INGESTING PVN OPERATIONAL DATA ---")

# Simulating a specific "Flaring Reduction Equipment Procurement" workflow
# This maps to Challenge 1 (Complex Processes) & Challenge 2 (Methane Reduction)
data = {
    'Step_ID': [1, 2, 3, 4, 5, 6, 7],
    'Department': [
        'Offshore Operations',
        'Technical Safety',
        'Procurement Dept',
        'Compliance (Internal)',
        'Ministry of Industry (Ext)',
        'Finance',
        'Deployment'
    ],
    'Activity': [
        'Identify Flaring Issue',
        'Tech Spec Approval',
        'Vendor Bidding',
        'Sustainability Audit',
        'Regulatory Permit',
        'Budget Release',
        'Install Equipment'
    ],
    'Time_Days': [2, 5, 14, 7, 20, 10, 30], # Note: Regulatory Permit is long
    'Next_Step_ID': [2, 3, 4, 5, 6, 7, None]
}

df = pd.DataFrame(data)
display(df[['Department', 'Activity', 'Time_Days']])

# ==========================================
# PART 2: GRAPH ENGINEERING (The "Math")
# ==========================================
print("\n--- 2. BUILDING KNOWLEDGE GRAPH ---")

G = nx.DiGraph()

# Build nodes and edges
for _, row in df.iterrows():
    # Add Node with metadata
    G.add_node(row['Department'], activity=row['Activity'], time=row['Time_Days'])

    # Add Edge to next step (if exists)
    if pd.notna(row['Next_Step_ID']):
        next_row = df[df['Step_ID'] == row['Next_Step_ID']]
        if not next_row.empty:
            next_dept = next_row.iloc[0]['Department']
            G.add_edge(row['Department'], next_dept, weight=row['Time_Days'])

# A. Calculate Total Workflow Time (Critical Path)
total_time = sum(nx.get_edge_attributes(G, 'weight').values())

# B. Identify "Bottleneck" using Betweenness Centrality
# (Which node controls the flow the most?)
centrality = nx.betweenness_centrality(G, weight='weight')
bottleneck_dept = max(centrality, key=centrality.get)
bottleneck_time = df[df['Department'] == bottleneck_dept]['Time_Days'].values[0]

graph_context = (
    f"Workflow: Flaring Reduction Retrofit. "
    f"Total Cycle Time: {total_time} days. "
    f"Detected Bottleneck: {bottleneck_dept} taking {bottleneck_time} days."
)

print(f"📊 ANALYTICS: {graph_context}")

# ==========================================
# PART 3: INTERACTIVE VISUALIZATION
# ==========================================
print("\n--- 3. GENERATING VISUAL TWIN (HTML) ---")

def show_graph(graph):
    net = Network(notebook=True, height="400px", width="100%", bgcolor="#222222", font_color="white", cdn_resources='in_line')

    # Add nodes with custom colors based on time (Red = Slow)
    for node, attrs in graph.nodes(data=True):
        color = "#ff4d4d" if attrs.get('time', 0) > 10 else "#00b894" # Red if > 10 days
        net.add_node(node, label=node, title=f"Activity: {attrs.get('activity')}\nTime: {attrs.get('time')} days", color=color)

    for source, target, attrs in graph.edges(data=True):
        net.add_edge(source, target, width=3, color="white")

    net.show("pvn_graph.html")
    return HTML("pvn_graph.html")

# Render the interactive graph
display(show_graph(G))

